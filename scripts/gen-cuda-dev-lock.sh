#!/bin/bash
# Regenerate official-templates/base/cuda-dev/<cuda>-ubuntu<ubuntu>.txt: the
# NVIDIA packages that nvidia/cuda:<cuda>-cudnn-devel-ubuntu<ubuntu> adds over
# -cudnn-runtime, pinned to the exact versions the devel image ships. Versions
# differ between Ubuntu releases, so each pair has its own file. Run it when a
# CUDA version or an Ubuntu release for one is added to versions.hcl.
#
# Usage: scripts/gen-cuda-dev-lock.sh <cuda-version> [ubuntu-version]
#   e.g. scripts/gen-cuda-dev-lock.sh 13.2.0 24.04
set -euo pipefail

if [[ $# -lt 1 ]]; then
    echo "Usage: $0 <cuda-version> [ubuntu-version]" >&2
    exit 1
fi
cuda="$1"
ubuntu="${2:-24.04}"
out="$(dirname "$0")/../official-templates/base/cuda-dev/${cuda}-ubuntu${ubuntu}.txt"

# Installed (ii) or held (hi) packages maintained by NVIDIA, as pkg=version.
nvidia_pkgs() {
    docker run --rm --platform linux/amd64 --entrypoint dpkg-query \
        "nvidia/cuda:${cuda}-cudnn-$1-ubuntu${ubuntu}" \
        -W -f='${db:Status-Abbrev}\t${Package}=${Version}\t${Maintainer}\n' |
        awk -F'\t' '$1 ~ /^[ih]i/ && $3 ~ /@nvidia\.com/ { print $2 }' |
        sort
}

{
    echo "# CUDA ${cuda} dev packages: what nvidia/cuda:${cuda}-cudnn-devel-ubuntu${ubuntu} adds"
    echo "# over -cudnn-runtime, at the exact versions it ships."
    echo "# Generated by scripts/gen-cuda-dev-lock.sh ${cuda} ${ubuntu}; do not edit by hand."
    comm -13 <(nvidia_pkgs runtime) <(nvidia_pkgs devel)
} > "${out}"

echo "wrote ${out} ($(grep -vc '^#' "${out}") packages)"
